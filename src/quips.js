export function pickQuip(id, look, last) {
  const list = QUIPS[id]?.[Math.max(0, Math.min(4, look - 1))];
  if (!list) return '';
  let s; do { s = list[Math.floor(Math.random() * list.length)]; } while (list.length > 1 && s === last);
  return s;
}
